# Convert class weights to TensorFlow tensor
class_weights_tensor = tf.constant(
    [class_weights[i] for i in range(num_classes)],
    dtype=tf.float32
)

# Assign a weight to each image
def add_sample_weights(images, labels):

    # Get class index from one-hot label
    class_ids = tf.argmax(
        labels,
        axis=1,
        output_type=tf.int32
    )

    # Get the corresponding weight
    sample_weights = tf.gather(
        class_weights_tensor,
        class_ids
    )

    return images, labels, sample_weights


