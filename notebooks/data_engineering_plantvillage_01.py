"""# **Augmentation**"""

# Create augmentation layers only once
rotation_layer = tf.keras.layers.RandomRotation(
    factor=0.25,
    fill_mode='reflect'
)

zoom_layer = tf.keras.layers.RandomZoom(
    height_factor=(-0.15, 0.15),
    width_factor=(-0.15, 0.15),
    fill_mode='reflect'
)

def augment_image(image):
    image = rotation_layer(image, training=True)
    image = zoom_layer(image, training=True)
    return image

